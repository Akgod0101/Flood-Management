// Generator for 12-hour demo historical series
function generateDemoHistory(baseValue: number, variance: number, trend: number): { time: string; value: number }[] {
  const points = [];
  for (let i = 11; i >= 0; i--) {
    const noise = Math.sin(i * 0.9) * variance;
    const trendEffect = (11 - i) * trend;
    const val = Math.max(0.1, parseFloat((baseValue + noise + trendEffect).toFixed(2)));
    points.push({
      time: `T-${i}h`,
      value: val,
    });
  }
  return points;
}

function generateDemoRainfallHistory(currentRain: number): { time: string; value: number }[] {
  const points = [];
  for (let i = 11; i >= 0; i--) {
    const pulse = Math.max(0, Math.sin((11 - i) * 0.5) * currentRain * 1.3);
    const val = parseFloat((pulse + (i === 0 ? currentRain : Math.random() * 2)).toFixed(1));
    points.push({
      time: `T-${i}h`,
      value: val,
    });
  }
  return points;
}

